audio_start:
    ; pthread_create(&audio_tid, NULL, audio_thread, NULL)
    lea     rdi, [rel audio_tid]
    xor     esi, esi
    lea     rdx, [rel audio_thread]
    xor     ecx, ecx
    call    pthread_create
    ret

