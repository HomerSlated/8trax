; ── event_loop ─────────────────────────────────────────────────────────────────
event_loop:
.frame:
    ; TODO: update iTime uniform (glUniform1f)
    ; TODO: glClear + glDrawArrays (full-screen quad via gl_VertexID trick)
    ; TODO: glXSwapBuffers

    ; Drain all queued events without blocking, then render next frame.
.drain:
    mov     rdi, [rel display]
    call    XPending
    test    eax, eax
    jz      .frame              ; no events — go render

    mov     rdi, [rel display]
    lea     rsi, [rel xevent]
    call    XNextEvent

    mov     eax, [rel xevent]   ; event->type (first field)
    cmp     eax, DestroyNotify
    je      do_exit
    cmp     eax, KeyPress
    jne     .drain

    ; XLookupKeysym(&xevent, 0) — layout-agnostic keysym lookup
    lea     rdi, [rel xevent]
    xor     esi, esi
    call    XLookupKeysym
    cmp     rax, XK_Escape
    jne     .drain

; ── clean exit ─────────────────────────────────────────────────────────────────
do_exit:
    mov     eax, 60             ; sys_exit
    xor     edi, edi            ; status = 0
    syscall
