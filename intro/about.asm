; ───────────────────────────────────────────────────────────────────────────────
section .data

sz_display  db ":0", 0
sz_pcm      db "default", 0

glx_attr    dd GLX_RGBA, GLX_DOUBLEBUFFER
            dd GLX_RED_SIZE,   8
            dd GLX_GREEN_SIZE, 8
            dd GLX_BLUE_SIZE,  8
            dd 0                    ; None

; ───────────────────────────────────────────────────────────────────────────────
section .bss

display     resq 1              ; Display*
screen      resd 1              ; int
root        resq 1              ; Window  (root)
window      resq 1              ; Window  (ours)
glx_ctx     resq 1              ; GLXContext
vis_info    resq 1              ; XVisualInfo*
