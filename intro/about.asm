section .rodata

; Compressed shader source — generated by: make shader_blob.inc
; Symbols defined: shader_blob_srclen (uncompressed), shader_blob_zlen, shader_blob
%include "shader_blob.inc"

; Compressed SDF text atlas — generated by: make text_blob.inc
; Symbols defined: text_atlas_w, text_atlas_h, text_blob_zlen, text_blob
%include "text_blob.inc"

; Full-screen triangle via gl_VertexID — no VBO needed.
; i=0→(-1,-1), i=1→(3,-1), i=2→(-1,3); GPU clips to viewport.
sz_vert_src:
    db "#version 330 core", 10
    db "void main(){int i=gl_VertexID;", 10
    db "vec2 p=vec2(float((i<<1)&2),float(i&2));", 10
    db "gl_Position=vec4(p*2.0-1.0,0.0,1.0);}", 0

sz_iTime        db "iTime", 0
sz_iResolution  db "iResolution", 0
sz_wm_class     db "about", 0, "About", 0   ; WM_CLASS: instance=about, class=About

align 4
f_ns_inv        dd 1.0e-9       ; nanoseconds → seconds conversion factor
f_one           dd 1.0          ; alpha=1.0 for glClearColor

; ───────────────────────────────────────────────────────────────────────────────
section .data

sz_display  db ":0", 0
sz_pcm      db "default", 0

glx_attr    dd GLX_RGBA, GLX_DOUBLEBUFFER
            dd GLX_RED_SIZE,   8
            dd GLX_GREEN_SIZE, 8
            dd GLX_BLUE_SIZE,  8
            dd 0                    ; None

; ───────────────────────────────────────────────────────────────────────────────
section .bss

