time_loc    resd 1              ; GLint — iTime uniform location
res_loc     resd 1              ; GLint — iResolution uniform location
pcm_handle  resq 1              ; snd_pcm_t*
audio_tid   resq 1              ; pthread_t
xevent      resb 192            ; XEvent  (large enough for all subtypes)
decomp_buf  resb (64 * 1024)    ; shader source after zlib decompression
decomp_len  resq 1              ; decompressed byte count (for glShaderSource)

; ───────────────────────────────────────────────────────────────────────────────
section .text

; ── entry point ────────────────────────────────────────────────────────────────
_start:
    ; sub rsp, 8 shifts the stack so that every subsequent `call` delivers
    ; the callee with rsp%16 == 0 — the alignment library code expects.
    ; _start never returns; we exit via sys_exit.
    sub     rsp, 8

    call    x11_open
    call    glx_init
    call    shader_init
    call    audio_start
    call    event_loop

; ── x11_open ───────────────────────────────────────────────────────────────────
x11_open:
    ; XOpenDisplay(":0")
    lea     rdi, [rel sz_display]
    call    XOpenDisplay
    mov     [rel display], rax

    ; XDefaultScreen(display)
    mov     rdi, rax
    call    XDefaultScreen
    mov     [rel screen], eax

    ; XDefaultRootWindow(display)
    mov     rdi, [rel display]
    call    XDefaultRootWindow
    mov     [rel root], rax

    ; XCreateSimpleWindow(display, root, 0, 0, WIN_W, WIN_H, 0, 0, 0)
    ; Args 7-9 (border_width, border, background) go on the stack.
    ; Three qword pushes = 24 bytes; add one pad qword → 32 bytes total,
    ; keeping rsp 16-byte aligned before the call.
    mov     rdi, [rel display]
    mov     rsi, [rel root]
    xor     edx, edx            ; x = 0
    xor     ecx, ecx            ; y = 0
    mov     r8d, WIN_W
    mov     r9d, WIN_H
    sub     rsp, 8              ; alignment pad
    push    qword 0             ; background  (arg 9)
    push    qword 0             ; border      (arg 8)
    push    qword 0             ; border_width (arg 7)
    call    XCreateSimpleWindow
    add     rsp, 32
    mov     [rel window], rax

    ; XSelectInput(display, window, KeyPressMask | StructureNotifyMask)
    mov     rdi, [rel display]
    mov     rsi, [rel window]
    mov     edx, KeyPressMask | StructureNotifyMask
    call    XSelectInput

    ; TODO: suppress window decorations (_MOTIF_WM_HINTS or _NET_WM_WINDOW_TYPE_SPLASH)
    ; TODO: XMoveWindow to centre on screen after mapping

    ; XMapWindow(display, window)
    mov     rdi, [rel display]
    mov     rsi, [rel window]
    call    XMapWindow

    ret

; ── glx_init ───────────────────────────────────────────────────────────────────
glx_init:
    ; glXChooseVisual(display, screen, glx_attr)
    mov     rdi, [rel display]
    mov     esi, [rel screen]
    lea     rdx, [rel glx_attr]
    call    glXChooseVisual
    mov     [rel vis_info], rax

    ; glXCreateContext(display, vis_info, NULL, True)
    mov     rdi, [rel display]
    mov     rsi, [rel vis_info]
    xor     edx, edx            ; share_list = NULL
    mov     ecx, 1              ; direct = True
    call    glXCreateContext
    mov     [rel glx_ctx], rax

    ; glXMakeCurrent(display, window, ctx)
    mov     rdi, [rel display]
    mov     rsi, [rel window]
    mov     rdx, [rel glx_ctx]
    call    glXMakeCurrent

    ret

